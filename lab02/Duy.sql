CREATE PROCEDURE SP_SEL_NO_ENCRYPT
	@TenCLB NVARCHAR(100),
	@TenQG NVARCHAR(100)
AS
BEGIN
	SELECT
	CT.MACT, CT.HOTEN, CT.NGAYSINH, CT.DIACHI, CT.VITRI
	FROM CAUTHU CT
	JOIN CAULACBO CLB ON CT.MACLB = CLB.MACLB
	JOIN QUOCGIA QG ON CT.MAQG = QG.MAQG
	WHERE CLB.TENCLB = @TenCLB AND QG.TENQG = @TenQG
END;
GO

