DECLARE @sp_name NVARCHAR(MAX);
DECLARE @sp_definition NVARCHAR(MAX);
DECLARE @alter_script NVARCHAR(MAX);

DECLARE sp_cursor CURSOR FOR 
SELECT sm.object_id, OBJECT_NAME(sm.object_id) AS sp_name, sm.definition
FROM sys.sql_modules sm
JOIN sys.procedures p ON sm.object_id = p.object_id
WHERE p.is_ms_shipped = 0;

OPEN sp_cursor;
FETCH NEXT FROM sp_cursor INTO @sp_name, @sp_name, @sp_definition;

WHILE @@FETCH_STATUS = 0
BEGIN
    SET @alter_script = REPLACE(@sp_definition, 'CREATE PROCEDURE', 'ALTER PROCEDURE');
    SET @alter_script = REPLACE(@alter_script, 'create procedure', 'alter procedure');
    SET @alter_script = REPLACE(@alter_script, 'CREATE PROC', 'ALTER PROC');

    IF CHARINDEX('WITH ENCRYPTION', UPPER(@alter_script)) = 0
    BEGIN
        SET @alter_script = STUFF(@alter_script, CHARINDEX('AS', UPPER(@alter_script)), 0, 'WITH ENCRYPTION ');
        
        EXEC sp_executesql @alter_script;
        PRINT 'Encrypt SP: ' + @sp_name;
    END

    FETCH NEXT FROM sp_cursor INTO @sp_name, @sp_name, @sp_definition;
END

CLOSE sp_cursor;
DEALLOCATE sp_cursor;
GO

